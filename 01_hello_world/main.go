// 【1】package 声明：每个 .go 文件的第一行必须是 package。
// 同一个目录下的所有文件必须属于同一个 package。
// 【重点】package main 表示"可执行程序"，必须包含 main 函数；
//         其他名字（如 package utils）表示"库代码"，不能直接运行。
package main

// 【2】import：导入需要用到的包。单个包可以单独一行，多个包用括号分组。
import (
	"fmt"     // fmt 是格式化输入输出包（Format 的缩写，发音 /fomt/）
	"strings" // 字符串工具包
)

// 其他导入写法（了解即可）：
//
//	import "fmt"                       // 单个导入
//	import f "fmt"                     // 别名导入：之后用 f.Println 调用
//	import _ "some/driver"             // 匿名导入：只触发包的 init()，不调用其中的函数
//
// 注意：导入了却没使用的包会导致【编译错误】（Go 强制保持代码整洁）。

// 【3】main 函数：程序入口。main 包中的 main 函数是可执行程序的起点，
// 它没有参数、没有返回值。
func main() {
	// ---------- 三种最常用的输出 ----------
	fmt.Println("Hello, World!")           // Println：打印后自动换行，多个参数用空格分隔
	fmt.Print("不换行, ", "参数间也不加空格") // Print：原样打印，不换行不加空格
	fmt.Println()                          // 单独换行
	fmt.Printf(" Printf 带格式化: %s = %d\n", "1+1", 2)

	// 常用格式化动词（verb）：
	//   %v   变量的默认格式（最万能）
	//   %+v  结构体时附带字段名
	//   %#v  Go 语法表示形式
	//   %T   变量的类型
	//   %d   整数    %f 浮点数    %.2f 保留两位小数
	//   %s   字符串  %q 带引号的字符串  %t 布尔值
	//   %x   十六进制  \n 换行  \t 制表符
	fmt.Printf("类型=%T 值=%v 引用=%q\n", "Go语言", "Go语言", "Go语言")

	// ---------- 使用导入的包 ----------
	fmt.Println(strings.ToUpper("hello"), strings.Repeat("Go", 3))

	// ---------- 注释的三种写法 ----------
	// 1. 单行注释：两个斜杠
	/* 2. 块注释：可以跨多行 */
	// 3. 文档注释：写在包/函数/类型声明上方，以标识符名开头的注释，
	//    可用 `go doc` 查看，也会展示在 pkg.go.dev 上（如下）：

	// sayHi 是一个演示用的函数（这行就是文档注释）
	sayHi("Gopher")
}

// sayHi 向指定的人问好
// 注意：参数需要声明类型 (name string)，写在小括号内。
func sayHi(name string) {
	fmt.Printf("你好, %s!\n", name)
}

